# 後綴具體度：數字越細越具體，越具體越優先
#   ⚠️ 存在原因（真實 bug）：
#     「福岡県糟屋郡粕屋町長者原東1-12-15」
#     「糟屋郡」同「粕屋町」一樣 3 個字，字典順序令「糟屋郡」贏，
#     結果 city = 糟屋郡（唔應該），正確係 粕屋町。
_SUFFIX_RANK = {
    "区": 0, "區": 0, "市": 1, "町": 2, "村": 3, "郡": 4,
    "洞": 0, "街": 1, "路": 2,
}


def place_sort_key(word: str) -> tuple[int, int, int]:
    """地名排序：字數越長越優先，然後後綴越具體越優先。"""
    rank = next((r for suf, r in _SUFFIX_RANK.items() if word.endswith(suf)), 9)
    return (-len(word), rank, word)


def sorted_places(words) -> list[str]:
    return sorted(words, key=place_sort_key)


def match_region(text: str, words: list[str] | None = None):
    """
    喺 text 入面搵最早出現、而且最長嘅地區名。

    回傳 (word, segment, index) 或 None。
    segment 係由命中位置起計嘅一小段窗（避免成句宣傳文案變成「地址」）。
    """
    words = words or ALL_DISTRICT_WORDS
    best = None                     # (word, index)
    for w in words:
        i = text.find(w)
        if i < 0:
            continue
        if best is None or i < best[1] or (i == best[1] and len(w) > len(best[0])):
            best = (w, i)
    if best is None:
        return None
    w, i = best
    seg = text[i:i + len(w) + 12]
    for sep in "，,。！!？?、；;｜|（(【〖\n":
        seg = seg.split(sep)[0]
    return w, seg.strip(), i


# 番地表達式（町名後面嘅數字部分）
_BANCHI = r"\d+(?:[-ー–－]\d+)*"


def tail_address(addr: str) -> str:
    """
    由地址字串抽「町名／街名 + 門牌號」，剝走都道府縣市區。

    例：
        大阪府大阪市中央区道頓堀1-5-10        → 道頓堀1-5-10
        神奈川県横浜市鶴見区大黒ふ頭15         → 大黒ふ頭15
        ソウル特別市 城東区 聖水洞2街 315-71   → 315-71
        서울 성동구 연무장길 47               → 47
        台北市大安區永康街 12 號              → 永康街12 號

    ⚠️ 呢個函式踩過好多坑，改之前一定要睇：
      1. 唔可以用 regex 猜都道府縣（「.{2,3}[縣県府]」會撞到「新宿区」）
      2. 唔可以用貪婪 regex 由左邊開始食（「東京都渋谷区」會變「京都渋谷区」）
      3. 單字後綴（区/市/町）唔可以無條件剝，否則「道頓堀」變「頓堀」
      4. 「歌舞伎町」呢種町名入面有「町」，所以唔可以見「町」就當行政後綴
      5. 台灣／韓國嘅「號」同數字之間可能有空格
      6. 「番地」係日本概念，但韓國／台灣嘅門牌號一樣有用 → 唔可以一律掉
    """
    if not addr:
        return ""

    cleaned = addr
    for ch in "（）()「」【】〖〗":
        cleaned = cleaned.replace(ch, " ")
    cleaned = re.sub(r"^〒?\s*\d{3}-?\d{4}\s*", "",
                     cleaned.replace("\u3000", " ")).strip()

    # ⓪ 最快路徑：最後一個空白段落本身就係門牌（韓國／台灣／有空格嘅地址）
    parts = [p for p in cleaned.split() if p]
    if len(parts) >= 2:
        last = parts[-1]
        if any(c.isdigit() for c in last) and len(last) <= 24:
            return _strip_admin_prefix(last)

    # ① 搵最後一組數字（連可選嘅「-x-y」同「號」）
    matches = list(re.finditer(r"\d+(?:\s?[-ー–－]\d+)*\s?[號号]?", cleaned))
    if not matches:
        return ""
    m = matches[-1]
    num = re.sub(r"\s+", " ", m.group(0)).strip()
    before = cleaned[:m.start()]

    # ② 數字後面唔可以有嘢（否則唔係門牌，例如「2丁目」入面嘅 2）
    after = cleaned[m.end():].strip()
    if after:
        return ""

    # ③ 攞門牌前面嘅町名／街名
    #    ⚠️ 一定要用固定窗（唔可以用 [^\d\s]{1,10}$），
    #       因為無界 regex 會由最左邊開始食，食埋「東京都新宿区」，
    #       然後 _strip_admin_prefix 剝完就變空。
    #       固定窗 [-10:] 保證最多睇 10 個字，之後靠 strip 剝行政前綴。
    name = ""
    window = before[-10:] if len(before) > 10 else before
    mname = re.search(r"([^\d\s]{1,10})$", window)
    if mname:
        raw = mname.group(1)
        name = _strip_admin_prefix(raw)
        # ⚠️ fallback：剝完變空（或者剝剩 1 個字）＝ 剝過龍，
        #    寧願用未剝嘅原文（好過完全冇資料）。
        #    呢個係「唔完美但唔會更差」嘅保守做法。
        if len(name) < 2:
            name = re.sub(r"^[都道府県県市区區郡町村洞]+", "", raw)
            if len(name) < 2:
                name = raw

    tail = (name + num).strip() if name else num
    return re.sub(r"\s{2,}", " ", tail).strip()


