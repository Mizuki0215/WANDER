# ⚠️ 唔可以用 regex 猜都道府縣（「.{2,3}[縣県府]」會撞到「新宿区」呢類），
#    一定要用明確清單。呢個係踩過嘅坑。
#    仲有個坑：唔可以用貪婪 regex 剝，否則「東京都渋谷区…」會由位置 1 開始
#    匹配（"京都渋谷区"），變成 "京都渋谷区神宮前1-2-3"。要逐個明確清單比對。
_ADMIN_PREFIX_GENERIC = re.compile(r"^[^\d]{1,3}[市区域郡町村]")
_ADMIN_SINGLE = re.compile(r"^[市区域郡町村都道府県県字]")

_PREFECTURES_SORTED = sorted(JP_PREFECTURES, key=len, reverse=True)


def _strip_admin_prefix(s: str) -> str:
    # ① 先剝都道府縣（明確清單，唔用 regex 猜）
    for pref in _PREFECTURES_SORTED:
        if s.startswith(pref):
            s = s[len(pref):]
            break
    # ② 再剝市／區／郡／町／村（最多幾層）
    for _ in range(4):
        before = s
        # 單字後綴只喺仲有足夠長度先剝，避免剝爛町名（例如「道頓堀」「新宿区」）
        # ⚠️ 一定要排喺 generic 之前，否則 generic 會照剝（佢唔知長度限制）
        if len(s) > 6:
            s = _ADMIN_SINGLE.sub("", s, count=1)
        s = _ADMIN_PREFIX_GENERIC.sub("", s, count=1)
        if s == before:
            break
    return s.strip()
