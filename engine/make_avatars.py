def obj(rows: list[str]) -> list[str]:
    """
    ⚠️ 自動將**空格**當做透明（'.'）——
       手打 grids 好易打咗空格當對齊，而空格係非法索引。
       （驗證器捉到 11 個，全部都係呢個原因。）
    """
    rows = [r.replace(' ', '.') for r in rows]
    assert len(rows) == N, f"要 {N} 行，實際 {len(rows)}"
    for i, r in enumerate(rows):
        assert len(r) == N, f"第 {i} 行要 {N} 格，實際 {len(r)}: {r!r}"
    return rows


