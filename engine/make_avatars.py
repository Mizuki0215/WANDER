# 每個頭像：pal 係 6 色（對應索引 0-5）
#   0=描邊 1=主 2=亮 3=深(五官) 4=點綴 5=白
def pal(dark, main, light, feature, accent):
    """動物用嘅 6 色（索引語意固定）。"""
    return [dark, main, light, feature, accent, '#ffffff']


def mkpal(*colors):
    """
    物件用嘅調色板 —— 可變長度。

    ⚠️ 物件嘅索引語意**每個都唔同**（扭計骰嘅 2 係綠色、
       相機嘅 2 係鏡頭灰），所以唔可以套用動物嘅 6 色語意。
       自動補齊到 8 色，避免「索引超出」呢類靜靜失敗。
    """
    out = list(colors)
    while len(out) < 8:
        out.append(out[-1])
    return out[:8]


