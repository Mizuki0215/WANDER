def validate() -> list[str]:
    bad = []
    ids = set()
    for a in AVATARS:
        if a['id'] in ids:
            bad.append(f"重複 id: {a['id']}")
        ids.add(a['id'])
        if not (4 <= len(a['pal']) <= 8):
            bad.append(f"{a['id']} pal 有 {len(a['pal'])} 色（要 4-8）")
        if len(a['grid']) != N:
            bad.append(f"{a['id']} 有 {len(a['grid'])} 行（要 {N}）")
        for i, row in enumerate(a['grid']):
            if len(row) != N:
                bad.append(f"{a['id']} 第 {i} 行 {len(row)} 格（要 {N}）: {row!r}")
            for j, ch in enumerate(row):
                if ch == '.':
                    continue
                if not ch.isdigit() or int(ch) >= len(a['pal']):
                    bad.append(f"{a['id']} ({i},{j}) 索引 {ch!r} 唔啱")
    return bad


def preview():
    from PIL import Image, ImageDraw
    cell, cols = 108, 8
    rows = (len(AVATARS) + cols - 1) // cols
    img = Image.new('RGB', (cols * cell, rows * (cell + 18)), (14, 8, 30))
    d = ImageDraw.Draw(img)
    for i, a in enumerate(AVATARS):
        ox = (i % cols) * cell + 14
        oy = (i // cols) * (cell + 18) + 10
        d.rounded_rectangle([ox - 4, oy - 4, ox + 84, oy + 84],
                            radius=20, fill=(38, 26, 72))
        c = 80 / N
        for y, row in enumerate(a['grid']):
            for x, ch in enumerate(row):
                if ch == '.':
                    continue
                h = a['pal'][int(ch)].lstrip('#')
                rgb = tuple(int(h[k:k + 2], 16) for k in (0, 2, 4))
                d.rectangle([ox + x * c, oy + y * c,
                             ox + (x + 1) * c - 0.6, oy + (y + 1) * c - 0.6], fill=rgb)
        d.text((ox + 40 - len(a['name']) * 3.5, oy + 88), a['name'], fill=(210, 200, 240))
    img = img.resize((int(img.width * 1.5), int(img.height * 1.5)), Image.LANCZOS)
    img.save('/tmp/avatars16.png')
    print(f'✓ /tmp/avatars16.png  ({len(AVATARS)} 個)')


def emit():
    lines = []
    lines.append('/**')
    lines.append(' * 像素頭像（16×16）')
    lines.append(' * ================')
    lines.append(' *')
    lines.append(' * ⚠️⚠️ 用戶要求：')
    lines.append(' *   「頭像嗰度…你嗰啲塑像風可唔可以整得**再 Q 啲**？')
    lines.append(' *    或者唔好咁簡陋啦，你整得再**精緻啲**都可以㗎。')
    lines.append(' *    同埋想要**多啲唔同嘅元素**都得㗎，例如豬、狗啦呢啲，')
    lines.append(' *    之後或者扭計骰啊、手機呀、鴨呀、兔仔呀呢啲都可以嘅。」')
    lines.append(' *')
    lines.append(' * ⚠️ 為咩由 8×8 升到 16×16：')
    lines.append(' *   · 8×8 嘅眼只可以係 1 格 → 做唔到「大眼 + 高光」= 唔 Q')
    lines.append(' *   · 8×8 做唔到腮紅、鼻、嘴同時存在')
    lines.append(' *')
    lines.append(' * ⚠️ 調色板索引（所有頭像一致）：')
    lines.append(' *   0=描邊  1=主色  2=亮部  3=五官深色  4=點綴  5=白(眼高光)')
    lines.append(' *')
    lines.append(' * ⚠️ 由 engine/make_avatars.py 生成 —— 唔好手改呢個檔案。')
    lines.append(' */')
    lines.append('')
    lines.append('export const PIXEL_AVATARS = [')
    for a in AVATARS:
        lines.append('  {')
        lines.append(f"    id: '{a['id']}', name: '{a['name']}',")
        lines.append("    pal: [" + ', '.join(f"'{c}'" for c in a['pal']) + "],")
        lines.append('    grid: [')
        for r in a['grid']:
            lines.append(f"      '{r}',")
        lines.append('    ],')
        lines.append('  },')
    lines.append(']')
    lines.append('')
    lines.append('export const AVATAR_IDS = PIXEL_AVATARS.map(a => a.id)')
    lines.append('export const AVATAR_MAP = Object.fromEntries('
                 'PIXEL_AVATARS.map(a => [a.id, a]))')
    lines.append('')
    lines.append('/** 舊資料可能係 URL（相片）→ 判斷係唔係像素 id。 */')
    lines.append('export function isPixelAvatar(v) {')
    lines.append('  return !!v && !!AVATAR_MAP[v]')
    lines.append('}')
    lines.append('')
    lines.append('/**')
    lines.append(' * 建立像素頭像嘅 SVG 字串。')
    lines.append(' *')
    lines.append(' * ⚠️ 用 SVG 而唔用 canvas：')
    lines.append(' *   SVG 可以喺任何 size 都保持銳利（shape-rendering=crispEdges），')
    lines.append(' *   而且可以直接塞入 React。')
    lines.append(' */')
    lines.append('export function avatarSvg(id, { size = 40, bg = null, '
                 'rounded = true } = {}) {')
    lines.append('  const a = AVATAR_MAP[id]')
    lines.append("  if (!a) return ''")
    lines.append('  const n = a.grid.length')
    lines.append('  const cell = size / n')
    lines.append('  const parts = [')
    lines.append('    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" '
                 'height="${size}"`,')
    lines.append('    ` viewBox="0 0 ${size} ${size}" '
                 'shape-rendering="crispEdges">`,')
    lines.append('  ]')
    lines.append('  if (bg) {')
    lines.append('    parts.push(`<rect width="${size}" height="${size}" '
                 'rx="${rounded ? size * 0.22 : 0}" fill="${bg}"/>`)')
    lines.append('  }')
    lines.append('  for (let y = 0; y < n; y++) {')
    lines.append('    const row = a.grid[y]')
    lines.append('    for (let x = 0; x < row.length; x++) {')
    lines.append("      const ch = row[x]")
    lines.append("      if (ch === '.') continue")
    lines.append('      const color = a.pal[Number(ch)] || a.pal[0]')
    lines.append('      parts.push(')
    lines.append('        `<rect x="${(x * cell).toFixed(2)}" '
                 'y="${(y * cell).toFixed(2)}" ` +')
    lines.append('        `width="${cell.toFixed(2)}" '
                 'height="${cell.toFixed(2)}" fill="${color}"/>`)')
    lines.append('    }')
    lines.append('  }')
    lines.append("  parts.push('</svg>')")
    lines.append("  return parts.join('')")
    lines.append('}')
    lines.append('')
    lines.append('/** 隨機揀一個（新用戶預設）。 */')
    lines.append('export function randomAvatar() {')
    lines.append('  return AVATAR_IDS[Math.floor(Math.random() * AVATAR_IDS.length)]')
    lines.append('}')
    lines.append('')
    AVATARS_JS.write_text('\n'.join(lines), encoding='utf-8')
    print(f'✓ 寫入 {AVATARS_JS}')
    print(f'  {len(AVATARS)} 個頭像 × {N}×{N}')


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--preview', action='store_true')
    ap.add_argument('--emit', action='store_true')
    args = ap.parse_args()

    build()
    bad = validate()
    if bad:
        print(f'⚠️ {len(bad)} 個問題：')
        for b in bad[:15]:
            print('  ', b)
        return 1
    print(f'✓ {len(AVATARS)} 個頭像，全部 {N}×{N}、索引正確')

    if args.preview:
        preview()
    if args.emit:
        emit()
    return 0


if __name__ == '__main__':
    sys.exit(main())
