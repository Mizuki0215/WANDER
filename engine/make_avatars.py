# 調色板索引嘅語意（所有頭像共用）
#   0 = 描邊（最暗）
#   1 = 主色
#   2 = 亮部（肚／面頰內側）
#   3 = 五官深色（眼／鼻）
#   4 = 點綴（腮紅／嘴／舌）
#   5 = 白（眼高光）


# ══════════════════════════════════════════════════════════════════
# 模板：Q 版動物臉
# ══════════════════════════════════════════════════════════════════
#
#  ⚠️ 關鍵比例（實測最好睇）：
#     · 頭佔 11 行（rows 4-14）= 68% 高度 → 典型 Q 版
#     · 眼喺 rows 8-9（頭嘅中下），每隻眼 3 格闊
#     · 高光一定要喺眼嘅**左上**（1 格）—— 冇高光就係「死魚眼」
#     · 腮紅喺 row 11（眼下面兩行），每邊 2 格
#     · 嘴喺 rows 12-13 中間

def _blank() -> list[list[str]]:
    return [['.'] * N for _ in range(N)]


def _row(g, y, x, s):
    for i, ch in enumerate(s):
        if 0 <= y < N and 0 <= x + i < N:
            g[y][x + i] = ch


def head(g, *, top=4, bottom=14, left=1, right=14, r=2):
    """
    畫頭 —— **圓角**矩形。

    ⚠️⚠️ 第一版嘅 bug：
       我用 `g[top+1][left] = '.'` 去切角，
       但 `(top+1, left)` 係**側邊描邊嘅其中一格** →
       成條側邊喺嗰行斷開 → 個頭睇落「冇邊」。
       （實測：16×16 之下好明顯，個頭似一嚿色。）

    ✅ 正確做法：用「每行縮入幾多格」去砌圓角：
         row top      → 縮入 2
         row top+1    → 縮入 1
         row top+2    → 縮入 0（全闊）
      左右對稱，上下對稱。
    """
    for y in range(top, bottom + 1):
        d = min(y - top, bottom - y)          # 距離最近嘅上下邊
        inset = max(0, r - d)
        x0, x1 = left + inset, right - inset
        for x in range(x0, x1 + 1):
            edge = (x == x0 or x == x1 or y == top or y == bottom)
            g[y][x] = '0' if edge else '1'


def face(g, *, eye_y=8, eye_dx=4, eye_w=3, eye_h=2,
         blush=True, mouth='w', nose=None):
    """
    畫五官。

    ⚠️ 眼一定要有**高光**（5）喺左上 —— 呢個係「Q」嘅關鍵。
    mouth: 'w'（W 形貓嘴）/ 'o'（圓嘴）/ 'v'（三角）/ 's'（微笑線）
    """
    cx = N // 2
    for sx in (-1, 1):
        ex = cx + sx * eye_dx - (eye_w // 2)
        for dy in range(eye_h):
            for dx in range(eye_w):
                g[eye_y + dy][ex + dx] = '3'
        # 高光（左上 1 格）—— 冇呢格就唔 Q
        g[eye_y][ex] = '5'

    if nose is not None:
        g[nose][cx - 1] = '3'
        g[nose][cx] = '3'

    my = eye_y + eye_h + 2
    if mouth == 'w':
        # 貓嘴：兩邊向上
        g[my][cx - 2] = '4'; g[my][cx + 1] = '4'
        g[my + 1][cx - 1] = '4'; g[my + 1][cx] = '4'
    elif mouth == 'o':
        g[my][cx - 1] = '3'; g[my][cx] = '3'
        g[my + 1][cx - 1] = '3'; g[my + 1][cx] = '3'
    elif mouth == 'v':
        g[my][cx - 2] = '4'; g[my][cx + 1] = '4'
        g[my + 1][cx - 1] = '4'; g[my + 1][cx] = '4'
        g[my + 2][cx] = '4'
    elif mouth == 's':
        for dx in (-2, -1, 1, 2):
            g[my][cx + dx] = '3'
        g[my + 1][cx] = '3'

    if blush:
        by = eye_y + eye_h + 1
        for sx in (-1, 1):
            bx = cx + sx * 5
            g[by][bx] = '4'
            g[by][bx + (1 if sx < 0 else -1)] = '4'


# ── 耳朵 ──────────────────────────────────────────────────────────

def ears_cat(g):
    """尖耳（三角）。"""
    for sx, x0 in ((-1, 1), (1, 10)):
        for i in range(3):
            _row(g, 1 + i, x0 + (2 - i if sx < 0 else i), '0')
        for i in range(2):
            g[2 + i][x0 + (1 - i if sx < 0 else i + 1)] = '1'
    # ⚠️ 耳仔要「坐」喺頭頂（row 4）上面，唔可以浮
    g[3][2] = g[3][3] = '1'
    g[3][12] = g[3][13] = '1'


def ears_round(g):
    """圓耳（熊／豬）。"""
    for x0 in (1, 12):
        for dy in range(3):
            for dx in range(3):
                g[2 + dy][x0 + dx] = '0'
        g[3][x0 + 1] = '1'
        g[4][x0] = g[4][x0 + 2] = '1'


def ears_long(g):
    """長耳（兔）—— 一直伸到頂。"""
    for x0 in (3, 10):
        for y in range(0, 5):
            for dx in range(3):
                g[y][x0 + dx] = '0'
        for y in range(1, 5):
            g[y][x0 + 1] = '2'


def ears_floppy(g):
    """垂耳（狗）。"""
    for sx, x0 in ((-1, -1), (1, 13)):
        for y in range(4, 10):
            col = x0 + (1 if sx > 0 else 0)
            g[y][col] = '0'
            g[y][col + (1 if sx < 0 else -1)] = '1'


def ears_panda(g):
    """熊貓圓黑耳。"""
    for x0 in (0, 12):
        for dy in range(4):
            for dx in range(4):
                y, x = 1 + dy, x0 + dx
                if 0 <= y < N and 0 <= x < N:
                    g[y][x] = '3'
    # 頭頂補返
    for x in range(1, 15):
        if g[4][x] == '.':
            g[4][x] = '0'


def ears_duck(g):
    """鴨：冇耳，改為嘴。"""
    g[10][N // 2 - 2] = '4'; g[10][N // 2 - 1] = '4'
    g[10][N // 2] = '4'; g[10][N // 2 + 1] = '4'
    g[11][N // 2 - 1] = '4'; g[11][N // 2] = '4'


# ══════════════════════════════════════════════════════════════════
# 生成器
# ══════════════════════════════════════════════════════════════════

def animal(ears=None, eye_dx=4, mouth='w', nose=None,
           blush=True, spots=None, beak=False):
    g = _blank()
    if ears == 'long':
        ears_long(g)
    head(g)
    if ears == 'cat':
        ears_cat(g)
    elif ears == 'round':
        ears_round(g)
    elif ears == 'floppy':
        ears_floppy(g)
    elif ears == 'panda':
        ears_panda(g)
    if beak:
        ears_duck(g)
        face(g, eye_y=7, eye_dx=4, mouth='none', blush=blush)
    else:
        face(g, eye_y=8, eye_dx=eye_dx, mouth=mouth, nose=nose, blush=blush)
    if spots:
        for (y, x) in spots:
            g[y][x] = '2'
    return [''.join(r) for r in g]


