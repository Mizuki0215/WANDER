export const AVATAR_IDS = PIXEL_AVATARS.map(a => a.id)
export const AVATAR_MAP = Object.fromEntries(PIXEL_AVATARS.map(a => [a.id, a]))

/** 舊資料可能係 URL（相片）→ 判斷係唔係像素 id。 */
export function isPixelAvatar(v) {
  return !!v && !!AVATAR_MAP[v]
}

/**
 * 建立像素頭像嘅 SVG 字串。
 *
 * ⚠️ 用 SVG 而唔用 canvas：
 *   SVG 可以喺任何 size 都保持銳利（shape-rendering=crispEdges），
 *   而且可以直接塞入 React。
 */
export function avatarSvg(id, { size = 40, bg = null, rounded = true } = {}) {
  const a = AVATAR_MAP[id]
  if (!a) return ''
  const n = a.grid.length
  const cell = size / n
  const parts = [
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}"`,
    ` viewBox="0 0 ${size} ${size}" shape-rendering="crispEdges">`,
  ]
  if (bg) {
    parts.push(`<rect width="${size}" height="${size}" rx="${rounded ? size * 0.22 : 0}" fill="${bg}"/>`)
  }
  for (let y = 0; y < n; y++) {
    const row = a.grid[y]
    for (let x = 0; x < row.length; x++) {
      const ch = row[x]
      if (ch === '.') continue
      const color = a.pal[Number(ch)] || a.pal[0]
      parts.push(
        `<rect x="${(x * cell).toFixed(2)}" y="${(y * cell).toFixed(2)}" ` +
        `width="${cell.toFixed(2)}" height="${cell.toFixed(2)}" fill="${color}"/>`)
    }
  }
  parts.push('</svg>')
  return parts.join('')
}

/** 隨機揀一個（新用戶預設）。 */
export function randomAvatar() {
  return AVATAR_IDS[Math.floor(Math.random() * AVATAR_IDS.length)]
}
