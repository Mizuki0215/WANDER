export const MASCOT_FRAMES = Object.keys(G)
export const MASCOT_SIZE = 16

/**
 * 建立吉祥物嘅 SVG。
 *
 * ⚠️ 同圖示一樣要 `shape-rendering="crispEdges"`。
 */
export function mascotSvg(frame = 'hello', { size = 96, bob = true } = {}) {
  const g = G[frame] || G.hello
  const n = g.grid.length
  const cell = size / n
  const out = [
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}"`,
    ` viewBox="0 0 ${size} ${size}" shape-rendering="crispEdges"`,
    bob ? ' class="mascot-bob"' : '', '>',
  ]
  for (let y = 0; y < n; y++) {
    const row = g.grid[y]
    for (let x = 0; x < row.length; x++) {
      const ch = row[x]
      if (ch === '.') continue
      const c = g.pal[Number(ch)] || g.pal[0]
      out.push(
        `<rect x="${(x * cell).toFixed(2)}" y="${(y * cell).toFixed(2)}" ` +
        `width="${cell.toFixed(2)}" height="${cell.toFixed(2)}" fill="${c}"/>`)
    }
  }
  out.push('</svg>')
  return out.join('')
}
