export const ALL_ICONS = { ...APP_ICONS, ...UI_ICONS }

/**
 * 建立像素圖示嘅 SVG 字串。
 *
 * ⚠️ `shape-rendering="crispEdges"` 係關鍵 ——
 *    冇佢瀏覽器會做 anti-aliasing，格與格之間會出現灰邊，
 *    就唔係「硬邊像素」嘅感覺。
 */
export function iconSvg(id, { size = 32, bg = null, radius = 0 } = {}) {
  const a = ALL_ICONS[id]
  if (!a) return ''
  const n = a.grid.length
  const cell = size / n
  const out = [
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}"`,
    ` viewBox="0 0 ${size} ${size}" shape-rendering="crispEdges">`,
  ]
  if (bg) {
    out.push(radius > 0
      ? `<rect width="${size}" height="${size}" rx="${radius}" fill="${bg}"/>`
      : `<rect width="${size}" height="${size}" fill="${bg}"/>`)
  }
  for (let y = 0; y < n; y++) {
    const row = a.grid[y]
    for (let x = 0; x < row.length; x++) {
      const ch = row[x]
      if (ch === '.') continue
      const c = a.pal[Number(ch)] || a.pal[0]
      out.push(
        `<rect x="${(x * cell).toFixed(2)}" y="${(y * cell).toFixed(2)}" ` +
        `width="${cell.toFixed(2)}" height="${cell.toFixed(2)}" fill="${c}"/>`)
    }
  }
  out.push('</svg>')
  return out.join('')
}

/** 彩色背景 + 白色圖示（主畫面 app icon 用）。 */
export function appIconSvg(id, { size = 56, grad }) {
  const svg = iconSvg(id, { size })
  if (!svg) return ''
  // 用外層 div 做背景（CSS 漸變），SVG 只畫圖
  return svg
}

export function hasIcon(id) {
  return !!ALL_ICONS[id]
}
